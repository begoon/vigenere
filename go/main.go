func installNgrams(table []float64, group ngramGroup, size int, smoothing float64) {
	letters := []rune(group.data)
	for start := 0; start+size <= len(letters); start += size {
		code := 0
		for i := 0; i < size; i++ {
			code = code*32 + letterIndex(letters[start+i])
		}
		table[code] = math.Log(float64(group.count) + smoothing)
	}
}

func loadLanguageScores() ([]float64, []float64) {
	tri := make([]float64, 32*32*32)
	quad := make([]float64, 32*32*32*32)
	for i := range tri {
		tri[i] = math.Log(.05)
	}
	for i := range quad {
		quad[i] = math.Log(.02)
	}
	for _, group := range triGroups {
		installNgrams(tri, group, 3, .05)
	}
	for _, group := range quadGroups {
		installNgrams(quad, group, 4, .02)
	}
	return tri, quad
}
